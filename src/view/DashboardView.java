    public void cargarDatos() {
        try {
            Connection conn = Conexion.getConnection();
            Statement stmt = conn.createStatement();

            ResultSet rs1 = stmt.executeQuery("SELECT COUNT(*) as total FROM habitante");
            if (rs1.next()) {
                lblTotalHabitantes.setText("Habitantes: " + rs1.getInt("total"));
            }

            ResultSet rs2 = stmt.executeQuery("SELECT COUNT(*) as total FROM vivienda");
            if (rs2.next()) {
                lblTotalViviendas.setText("Viviendas: " + rs2.getInt("total"));
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
    public void cargarDashboard() {
        try {
            Connection conn = Conexion.getConnection();
            Statement stmt = conn.createStatement();

            // 🔹 TOTAL HABITANTES
            ResultSet rs1 = stmt.executeQuery("SELECT COUNT(*) as total FROM habitante");
            if (rs1.next()) {
                lblTotalHabitantes.setText(rs1.getInt("total") + "");
            }

            // 🔹 TOTAL VIVIENDAS
            ResultSet rs2 = stmt.executeQuery("SELECT COUNT(*) as total FROM vivienda");
            if (rs2.next()) {
                lblTotalViviendas.setText(rs2.getInt("total") + "");
            }

            // 🔹 HABITANTES POR MUNICIPIO
            ResultSet rs3 = stmt.executeQuery(
                "SELECT m.nombre, COUNT(h.id) as total " +
                "FROM habitante h " +
                "JOIN vivienda v ON h.vivienda_id = v.id " +
                "JOIN municipio m ON v.municipio_id = m.id " +
                "GROUP BY m.nombre"
            );

            DefaultTableModel model = new DefaultTableModel();
            model.addColumn("Municipio");
            model.addColumn("Habitantes");

            while (rs3.next()) {
                model.addRow(new Object[]{
                    rs3.getString("nombre"),
                    rs3.getInt("total")
                });
            }

            tablaMunicipios.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
    public void cargarPorLocalidad() {
        try {
            Connection conn = Conexion.getConnection();
            Statement stmt = conn.createStatement();

            ResultSet rs = stmt.executeQuery(
                "SELECT l.nombre, COUNT(h.id) as total " +
                "FROM habitante h " +
                "JOIN vivienda v ON h.vivienda_id = v.id " +
                "JOIN localidad l ON v.localidad_id = l.id " +
                "GROUP BY l.nombre"
            );

            DefaultTableModel model = new DefaultTableModel();
            model.addColumn("Localidad");
            model.addColumn("Habitantes");

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("nombre"),
                    rs.getInt("total")
                });
            }

            TablaLocalidades.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
