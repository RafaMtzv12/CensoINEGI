    public void cargarTabla() {
    try {
        Connection conn = Conexion.getConnection();
        Statement stmt = conn.createStatement();

        ResultSet rs = stmt.executeQuery(
            "SELECT h.id, h.nombre, h.edad, h.sexo, v.tipo " +
            "FROM habitante h " +
            "JOIN vivienda v ON h.vivienda_id = v.id"
        );

        DefaultTableModel modelo = new DefaultTableModel();

        modelo.addColumn("ID");
        modelo.addColumn("Nombre");
        modelo.addColumn("Edad");
        modelo.addColumn("Sexo");
        modelo.addColumn("Vivienda");

        while (rs.next()) {
            Object[] fila = new Object[5];
            fila[0] = rs.getInt("id");
            fila[1] = rs.getString("nombre");
            fila[2] = rs.getInt("edad");
            fila[3] = rs.getString("sexo");
            fila[4] = rs.getString("tipo");

            modelo.addRow(fila);
        }

        tablaHabitantes.setModel(modelo);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
