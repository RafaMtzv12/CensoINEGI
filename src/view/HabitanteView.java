    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String nombre = txtNombre.getText().trim();
        String edadTexto = txtEdad.getText().trim();

        // 🔴 VALIDACIONES

        if (nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "El nombre es obligatorio");
            return;
        }

        if (edadTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "La edad es obligatoria");
            return;
        }

        // Validar número
        int edad;
        try {
            edad = Integer.parseInt(edadTexto);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "La edad debe ser un número");
            return;
        }

        // Validar sexo
        if (cbxSexo.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecciona un sexo");
            return;
        }

        // Validar vivienda
        if (cbxVivienda.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una vivienda");
            return;
        }

        // 🔵 SI TODO ESTÁ BIEN → GUARDAR

        String sexo = cbxSexo.getSelectedItem().toString();

        // obtener id vivienda
        String selected = cbxVivienda.getSelectedItem().toString();
        int vivienda_id = Integer.parseInt(selected.split(" - ")[0]);

        model.Habitante h = new model.Habitante();
        h.setNombre(nombre);
        h.setEdad(edad);
        h.setSexo(sexo);
        h.setVivienda_id(vivienda_id);

        new dao.HabitanteDAO().insertar(h);

        javax.swing.JOptionPane.showMessageDialog(this, "Habitante guardado");

        // opcional: limpiar campos
        txtNombre.setText("");
        txtEdad.setText("");        // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarActionPerformed

